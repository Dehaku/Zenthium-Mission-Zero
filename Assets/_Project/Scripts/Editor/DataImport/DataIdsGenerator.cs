using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace Zenthium.Editor.DataImport
{
    /// <summary>
    /// Writes the <c>DataIds</c> class of id constants, so code never names a data entry with a string literal.
    /// </summary>
    public static class DataIdsGenerator
    {
        public const string OutputPath = "Assets/_Project/Scripts/Data/Generated/DataIds.cs";

        private const string ClassName = "DataIds";
        private const string Newline = "\n";

        /// <returns>The source code, or null if two ids in a section give the same identifier,
        /// or an id can't be an identifier. The reasons are added to <paramref name="errors"/>.</returns>
        public static string Generate(ParsedDesignData data, List<string> errors)
        {
            int errorsBefore = errors.Count;
            var code = new StringBuilder();
            code.Append("// <auto-generated>").Append(Newline)
                .Append("// Written by Zenthium > Data > Import Design CSVs from Docs/design/data/. Don't edit by hand.").Append(Newline)
                .Append("// </auto-generated>").Append(Newline)
                .Append(Newline)
                .Append("namespace Zenthium.Data").Append(Newline)
                .Append("{").Append(Newline)
                .Append("    public static class ").Append(ClassName).Append(Newline)
                .Append("    {").Append(Newline);

            AppendSection(code, "Modules", Ids(data.Modules, m => m.Id), errors);
            AppendSection(code, "Factions", data.FactionIds, errors);
            AppendSection(code, "Entities", Ids(data.Entities, e => e.Id), errors);
            AppendSection(code, "Heroes", Ids(data.Heroes, h => h.Id), errors);
            AppendSection(code, "Props", Ids(data.Props, p => p.Id), errors);
            AppendSection(code, "Prices", Ids(data.Prices, p => p.Id), errors);
            AppendSection(code, "ValueKeys", ValueKeys(data), errors);

            code.Append("    }").Append(Newline)
                .Append("}").Append(Newline);
            return errors.Count == errorsBefore ? code.ToString() : null;
        }

        /// <returns>True if the file was missing or different and has been written.</returns>
        public static bool WriteIfChanged(string projectRoot, string code)
        {
            string path = Path.Combine(projectRoot, OutputPath);
            if (File.Exists(path) && File.ReadAllText(path) == code)
            {
                return false;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, code);
            return true;
        }

        private static void AppendSection(StringBuilder code, string sectionName, IEnumerable<string> ids, List<string> errors)
        {
            code.Append("        public static class ").Append(sectionName).Append(Newline)
                .Append("        {").Append(Newline);

            var used = new Dictionary<string, string>(StringComparer.Ordinal);
            foreach (string id in ids)
            {
                if (!IdentifierFormatter.TryFormat(id, out string identifier))
                {
                    errors.Add($"{sectionName}: '{id}' has no letters or digits to make an identifier from.");
                }
                else if (identifier == sectionName || identifier == ClassName)
                {
                    errors.Add($"{sectionName}: '{id}' would be named {identifier}, the same as its class; rename it.");
                }
                else if (used.TryGetValue(identifier, out string other))
                {
                    errors.Add($"{sectionName}: '{id}' and '{other}' would both be named {identifier}; rename one.");
                }
                else
                {
                    used.Add(identifier, id);
                    code.Append("            public const string ").Append(identifier)
                        .Append(" = \"").Append(Escape(id)).Append("\";").Append(Newline);
                }
            }

            code.Append("        }").Append(Newline)
                .Append(Newline);
        }

        private static IEnumerable<string> Ids<T>(List<T> records, Func<T, string> getId)
        {
            foreach (T record in records)
            {
                yield return getId(record);
            }
        }

        /// <summary>Every distinct key from the values columns, in file order.</summary>
        private static IEnumerable<string> ValueKeys(ParsedDesignData data)
        {
            var keys = new List<string>();
            var seen = new HashSet<string>(StringComparer.Ordinal);
            foreach (ModuleRecord module in data.Modules)
            {
                AddKeys(module.Values, keys, seen);
            }

            foreach (EntityRecord entity in data.Entities)
            {
                AddKeys(entity.Values, keys, seen);
            }

            return keys;
        }

        private static void AddKeys(List<ValueRecord> values, List<string> keys, HashSet<string> seen)
        {
            foreach (ValueRecord value in values)
            {
                if (seen.Add(value.Key))
                {
                    keys.Add(value.Key);
                }
            }
        }

        private static string Escape(string id)
        {
            return id.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }
    }
}
